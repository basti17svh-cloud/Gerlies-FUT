-- Footera V21.139 – atomic LIVE paid-pack settlement, staging only.
-- The authenticated edge function must generate the draw using the shared
-- server-side FooteraPackOdds engine. The browser cannot call this RPC.
-- All existing LIVE store items and pack blueprints stay disabled.
alter table public.footera_live_pack_specs
  add column if not exists catalog_version text not null default 'fc27-pending',
  add column if not exists draw_engine text not null default 'exact-weighted-subset-v1';

create or replace function public.footera_purchase_verified_live_pack(
 p_request_id uuid,
 p_user_id uuid,
 p_item_key text,
 p_spec_version text,
 p_player_ids text[]
) returns jsonb
language plpgsql security definer set search_path=''
as $$
declare
 v_previous public.footera_live_point_spends%rowtype;
 v_store public.footera_live_store_items%rowtype;
 v_spec public.footera_live_pack_specs%rowtype;
 v_balance bigint;
 v_player public.footera_live_player_catalog%rowtype;
 v_slot integer;
 v_group jsonb;
 v_slot_index integer:=0;
 v_j integer;
 v_rating smallint;
 v_guaranteed boolean:=false;
 v_card_count integer;
 v_ids jsonb;
 v_receipt public.footera_live_entitlements%rowtype;
begin
 if p_request_id is null or p_user_id is null or p_item_key is null or
    p_spec_version is null or p_player_ids is null then
  raise exception 'Missing LIVE pack purchase parameters';
 end if;
 -- Replay before catalogue lookup: a completed purchase is immutable even after retirement.
 select * into v_previous from public.footera_live_point_spends
  where id=p_request_id;
 if found then
  if v_previous.user_id is distinct from p_user_id or
     v_previous.item_key is distinct from p_item_key then
   raise exception 'LIVE request ID belongs to different user or item';
  end if;
  select * into v_receipt from public.footera_live_entitlements
    where spend_id=p_request_id and user_id=p_user_id and item_key=p_item_key;
  if not found or v_receipt.delivery_status<>'delivered' then
   raise exception 'Prior LIVE pack receipt not delivered';
  end if;
  select balance_points into v_balance from public.footera_live_points_wallets
    where user_id=p_user_id;
  return jsonb_build_object('status','already_processed',
   'request_id',p_request_id,'item_key',p_item_key,
   'points_cost',v_previous.points_cost,'balance',coalesce(v_balance,0),
   'delivery_status','delivered');
 end if;

 select * into v_store from public.footera_live_store_items
  where item_key=p_item_key and item_type='pack'
   and enabled=true and fulfillment_ready=true
   and (available_from is null or available_from<=now())
   and (available_until is null or available_until>now());
 if not found then raise exception 'LIVE pack is not available'; end if;

 select * into v_spec from public.footera_live_pack_specs
  where item_key=p_item_key and enabled=true and
   spec_version=p_spec_version and draw_engine='exact-weighted-subset-v1';
 if not found or v_spec.points_cost<>v_store.points_cost or
   v_spec.catalog_version='fc27-pending' then
  raise exception 'LIVE pack specification not approved';
 end if;
 if cardinality(p_player_ids) <> v_spec.player_count
    or cardinality(p_player_ids) <> (select count(distinct x)
       from unnest(p_player_ids) x) then
   raise exception 'LIVE pack draw count or uniqueness invalid';
 end if;
 -- The composition is a trusted server-signed definition.
 -- Reject a draw violating its rating bands or required rating guarantee.
 for v_group in select value from jsonb_array_elements(v_spec.composition)
 loop
  for v_j in 1..(v_group->>'count')::integer loop
   v_slot_index:=v_slot_index+1;
   if v_slot_index>v_spec.player_count then
    raise exception 'LIVE pack specification oversized';
   end if;
   select * into v_player from public.footera_live_player_catalog
    where player_id=p_player_ids[v_slot_index] and approved_for_paid=true
      and catalog_version=v_spec.catalog_version;
   if not found then raise exception 'Unapproved LIVE draw player or catalogue'; end if;
   v_rating:=v_player.base_rating;
   if v_rating<(v_group->>'min')::integer or
      v_rating>(v_group->>'max')::integer then
    raise exception 'LIVE pack draw rating outside slot range';
   end if;
   -- Guarantee belongs to first group that can contain it, as in the shared engine.
   if v_spec.guaranteed_rating>0 and
      (v_group->>'max')::integer>=v_spec.guaranteed_rating and
      not v_guaranteed and v_rating>=v_spec.guaranteed_rating then
    v_guaranteed:=true;
   end if;
  end loop;
 end loop;
 if v_slot_index<>v_spec.player_count or
    (v_spec.guaranteed_rating>0 and not v_guaranteed) then
  raise exception 'LIVE pack draw guarantee or slots invalid';
 end if;
 -- The verified player pool and draw are generated by the trusted edge service.
 -- A caller with anon/authenticated credentials cannot execute this procedure.
 insert into public.footera_live_point_spends(id,user_id,item_key,item_type,points_cost)
 values(p_request_id,p_user_id,p_item_key,'pack',v_store.points_cost);
 update public.footera_live_points_wallets set
  balance_points=balance_points-v_store.points_cost,updated_at=now()
 where user_id=p_user_id and balance_points>=v_store.points_cost
 returning balance_points into v_balance;
 if not found then raise exception 'Insufficient verified live Footera Points'; end if;
 for v_slot in 0..v_spec.player_count-1 loop
  insert into public.footera_live_cards(spend_id,user_id,item_key,slot,player_id,card_snapshot)
   values(p_request_id,p_user_id,p_item_key,v_slot,p_player_ids[v_slot+1],'{}'::jsonb);
 end loop;
 -- BEFORE INSERT entitlement trigger verifies exactly the approved full inventory.
 insert into public.footera_live_entitlements(spend_id,user_id,item_key,item_type)
 values(p_request_id,p_user_id,p_item_key,'pack');
 select * into v_receipt from public.footera_live_entitlements
  where spend_id=p_request_id;
 if v_receipt.delivery_status<>'delivered' then
  raise exception 'LIVE pack receipt not delivered';
 end if;
 return jsonb_build_object('status','spent',
  'request_id',p_request_id,'item_key',p_item_key,
  'points_cost',v_store.points_cost,'balance',v_balance,
  'delivery_status','delivered');
end;
$$;
revoke all on function public.footera_purchase_verified_live_pack(uuid,uuid,text,text,text[])
 from public,anon,authenticated;
grant execute on function public.footera_purchase_verified_live_pack(uuid,uuid,text,text,text[])
 to service_role;

-- Old S1 entitlement path remains untouched. Packs now require all N real cards.
create or replace function public.footera_live_validate_delivery()
returns trigger
language plpgsql security definer set search_path=''
as $$
declare
 v_store public.footera_live_store_items%rowtype;
 v_spec public.footera_live_pack_specs%rowtype;
 v_cards bigint;
 v_agg jsonb;
begin
 select * into v_store from public.footera_live_store_items
  where item_key=new.item_key and enabled=true and fulfillment_ready=true
    and (available_from is null or available_from<=now())
    and (available_until is null or available_until>now());
 if not found then raise exception 'Live item delivery is not ready'; end if;
 if v_store.item_type is distinct from new.item_type then
   raise exception 'Live entitlement type mismatch';
 end if;
 if new.item_type='season_pass' and new.item_key='season_pass:s1' then
   new.delivery_status:='delivered';
   new.delivery_payload:=jsonb_build_object('season_key','s1','premium',true);
   new.delivered_at:=now();
 elsif new.item_type='pack' then
   select * into v_spec from public.footera_live_pack_specs
    where item_key=new.item_key and enabled=true;
   if not found then raise exception 'LIVE pack spec missing'; end if;
   select count(*),jsonb_agg(jsonb_build_object('card_id',card_id,'slot',slot) order by slot)
      into v_cards,v_agg from public.footera_live_cards
      where spend_id=new.spend_id and user_id=new.user_id and item_key=new.item_key;
   if v_cards<>v_spec.player_count then
     raise exception 'Cannot deliver incomplete LIVE pack';
   end if;
   new.delivery_status:='delivered';
   new.delivery_payload:=jsonb_build_object('spec_version',v_spec.spec_version,
      'catalog_version',v_spec.catalog_version,'cards',v_agg);
   new.delivered_at:=now();
 else
   raise exception 'Live item fulfillment not implemented';
 end if;
 return new;
end;
$$;
revoke all on function public.footera_live_validate_delivery()
 from public,anon,authenticated;
grant execute on function public.footera_live_validate_delivery() to service_role;
